fun configuredUrl(propertyName: String, defaultValue: String): String =
    providers.gradleProperty(propertyName)
        .orElse(providers.environmentVariable(propertyName))
        .getOrElse(defaultValue)
        .let { value -> if (value.endsWith('/')) value else "$value/" }
        .replace("\\", "\\\\")
        .replace("\"", "\\\"")

